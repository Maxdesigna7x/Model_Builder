import assert from 'node:assert/strict';
import {build} from 'esbuild';
const bundle=await build({entryPoints:['frontend/src/model-groups.ts'],bundle:true,write:false,format:'esm',platform:'node'});
const {canGroup,createModelGroup,groupPath,groupRectangles,withGroups}=await import(`data:text/javascript;base64,${Buffer.from(bundle.outputFiles[0].text).toString('base64')}`);
const nodes=['i','a','b','c','d','o'].map((id,index)=>({id,position:{x:0,y:index*100},data:{label:id,blockType:id==='i'?'input':id==='o'?'output':'relu',properties:{}}}));
const edges=nodes.slice(1).map((n,i)=>({id:String(i),source:nodes[i].id,target:n.id}));
assert.ok(canGroup(nodes,edges,new Set(['a','b'])));
assert.ok(!canGroup(nodes,edges,new Set(['a','c'])),'disconnected selection skips b');
let grouped=createModelGroup(nodes,edges,new Set(['a','b']),{id:'inner',name:'Inner'});
assert.ok(!canGroup(grouped,edges,new Set(['a','b'])),'a complete group cannot be grouped with itself');
assert.ok(!canGroup(grouped,edges,new Set(['b','c'])),'cannot split an existing group boundary');
assert.ok(!canGroup(grouped,edges,new Set(['a','b','d'])),'whole group plus a non-adjacent card is rejected');
grouped=createModelGroup(grouped,edges,new Set(['a','b','c']),{id:'outer',name:'Outer'});
assert.deepEqual(groupPath(grouped.find(n=>n.id==='a')).map(g=>g.id),['outer','inner']);
assert.deepEqual(groupPath(grouped.find(n=>n.id==='c')).map(g=>g.id),['outer']);
const rects=groupRectangles(grouped),outer=rects.find(g=>g.id==='outer'),inner=rects.find(g=>g.id==='inner');
assert.ok(outer.x<inner.x&&outer.y<inner.y&&outer.right>inner.right&&outer.bottom>inner.bottom);
const ungrouped=grouped.map(n=>withGroups(n,groupPath(n).filter(g=>g.id!=='outer')));
assert.deepEqual(groupPath(ungrouped.find(n=>n.id==='a')).map(g=>g.id),['inner']);
const fork=[{id:'ia',source:'i',target:'a'},{id:'ib',source:'i',target:'b'},{id:'ac',source:'a',target:'c'},{id:'bc',source:'b',target:'c'}];
assert.ok(!canGroup(nodes,fork,new Set(['i','a'])),'partial fork cannot enclose unselected branch');
assert.ok(canGroup(nodes,fork,new Set(['i','a','b','c'])),'a complete consecutive branched region can be grouped');
console.log('Grouping: consecutive regions, skipped layers, atomic groups, nesting and ungrouping passed.');
